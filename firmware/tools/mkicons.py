#!/usr/bin/env python3
"""Rasterize Meteocons SVGs (MIT, Bas Milius, npm @bybas/weather-icons) into 16-colour
4-bit PROGMEM bitmaps pre-composited on black. Usage: mkicons.py <svg dir> <out.h>"""
import io, subprocess, sys
from PIL import Image

ICONS = [  # name, svg, box w, box h
    ("I_CLEAR_D", "clear-day", 60, 50), ("I_CLEAR_N", "clear-night", 60, 50),
    ("I_PARTLY_D", "partly-cloudy-day", 60, 50), ("I_PARTLY_N", "partly-cloudy-night", 60, 50),
    ("I_OVERCAST", "overcast", 60, 50), ("I_FOG", "fog", 60, 50), ("I_DRIZZLE", "drizzle", 60, 50),
    ("I_RAIN", "rain", 60, 50), ("I_SLEET", "sleet", 60, 50), ("I_SNOW", "snow", 60, 50),
    ("I_STORM", "thunderstorms-rain", 60, 50),
    ("I_THERMO", "thermometer", 30, 38), ("I_HUMID", "humidity", 30, 34),
    ("I_THERMO_S", "thermometer", 20, 26), ("I_HUMID_S", "humidity", 16, 16), ("I_WIND_S", "wind", 26, 17),
]


def render(svg_dir, svg, bw, bh):
    png = subprocess.run(["rsvg-convert", "-w", "512", "-h", "512", "-b", "black", f"{svg_dir}/{svg}.svg"],
                         check=True, capture_output=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGB")
    bbox = im.point(lambda v: 255 if v > 12 else 0).convert("L").getbbox()
    im = im.crop(bbox)
    s = min(bw / im.width, bh / im.height)
    im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.LANCZOS)
    q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:48]
    pal += [0] * (48 - len(pal))
    # make sure index of the darkest colour is used for background (it already is black)
    return q, pal


def c565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


if __name__ == "__main__":
    svg_dir, out = sys.argv[1], sys.argv[2]
    lines = ["// Generated by tools/mkicons.py from Meteocons by Bas Milius (MIT License). Do not edit.",
             "#pragma once", '#include "font.h"',
             "struct Icon { uint8_t w, h; uint16_t pal[16]; const uint8_t *px; };"]
    total = 0
    for name, svg, bw, bh in ICONS:
        q, pal = render(svg_dir, svg, bw, bh)
        w, h = q.size
        data = list(q.getdata())
        if len(data) % 2: data.append(0)
        packed = bytes((data[i] << 4) | data[i + 1] for i in range(0, len(data), 2))
        total += len(packed) + 32
        lines.append(f"static const uint8_t {name}_px[] PROGMEM = {{" + ",".join(f"0x{b:02x}" for b in packed) + "};")
        p565 = ",".join(f"0x{c565(*pal[i*3:i*3+3]):04x}" for i in range(16))
        lines.append(f"static const Icon {name} = {{{w}, {h}, {{{p565}}}, {name}_px}};")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"icons: {total/1024:.1f} KB")
