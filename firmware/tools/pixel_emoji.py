def image(name, scale, bg=(0, 0, 0)):
    """Render one icon at an integer scale as a Pillow RGB image."""
    from PIL import Image
    rows = [(r + "." * 16)[:16] for r in ICONS[name].strip("\n").split("\n")][:16]
    im = Image.new("RGB", (16, 16), bg)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in PAL:
                im.putpixel((x, y), PAL[ch])
    return im.resize((16 * scale, 16 * scale), Image.NEAREST)
