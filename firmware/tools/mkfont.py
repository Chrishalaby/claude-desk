#!/usr/bin/env python3
"""Generate 4-bit anti-aliased bitmap fonts (PROGMEM C header) from TTF/OTF files.

Glyph code 127 is the degree sign, 128 the middle dot.
"""
import math, sys
from PIL import ImageFont

INTER = "/usr/share/fonts/opentype/inter/"
ASCII = "".join(chr(c) for c in range(32, 127)) + "\u00b0\u00b7"
SPECS = [
    # name,       file,             px,  chars
    ("F_CLOCK", "Inter-Bold.otf", 68, "0123456789:"),
    ("F_TALL",  "InterDisplay-Bold.otf", 104, "0123456789:", 0.66),   # condensed tall clock
    ("F_TEMP",  "Inter-Bold.otf", 36, " -0123456789%\u00b0"),
    ("F_L",     "Inter-Bold.otf", 28, ASCII),
    ("F_M",     "Inter-SemiBold.otf", 19, ASCII),
    ("F_S",     "Inter-Medium.otf", 14, ASCII),
]


def code(ch):
    return {"\u00b0": 127, "\u00b7": 128}.get(ch, ord(ch))  # degree, middle dot


def gen(name, path, px, chars, xs=1.0):
    from PIL import Image
    f = ImageFont.truetype(INTER + path, px)
    top, bot = 0, 0
    chars = sorted(set(chars), key=code)
    first, last = code(chars[0]), code(chars[-1])
    bmp, glyphs = bytearray(), []
    by_code = {code(c): c for c in chars}
    for cp in range(first, last + 1):
        ch = by_code.get(cp)
        if ch is None or ch == " ":
            adv = round(f.getlength(" ")) if ch == " " else 0
            glyphs.append((len(bmp), 0, 0, 0, 0, adv))
            continue
        mask, (ox, oy) = f.getmask2(ch, mode="L", anchor="ls")
        mask = Image.frombytes("L", mask.size, bytes(mask))
        if xs != 1.0:
            mask = mask.resize((max(1, round(mask.size[0] * xs)), mask.size[1]), Image.LANCZOS)
            ox = round(ox * xs)
        w, h = mask.size
        adv = round(f.getlength(ch) * xs)
        top, bot = max(top, -oy), max(bot, oy + h)
        data = [mask.getpixel((x, y)) for y in range(h) for x in range(w)]
        q = [min(15, (v * 15 + 127) // 255) for v in data]
        if len(q) % 2:
            q.append(0)
        off = len(bmp)
        for i in range(0, len(q), 2):
            bmp.append((q[i] << 4) | q[i + 1])
        glyphs.append((off, w, h, ox, oy, adv))
    out = [f"// {name}: {path} {px}px, codes {first}..{last}"]
    out.append(f"static const uint8_t {name}_bmp[] PROGMEM = {{")
    for i in range(0, len(bmp), 24):
        out.append("  " + ",".join(f"0x{b:02x}" for b in bmp[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const AAGlyph {name}_g[] PROGMEM = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    # band = real glyph extents (so big digits don't repaint empty space above/below)
    out.append(f"static const AAFont {name} = {{{name}_bmp, {name}_g, {first}, {last}, {top}, {top + bot}}};")
    return "\n".join(out), len(bmp) + len(glyphs) * 8


if __name__ == "__main__":
    parts, total = ["// Generated by tools/mkfont.py from Inter (SIL Open Font License). Do not edit.",
                    "#pragma once", '#include "font.h"'], 0
    for s in SPECS:
        txt, n = gen(*s)
        parts.append(txt)
        total += n
    open(sys.argv[1], "w").write("\n".join(parts) + "\n")
    print(f"fonts: {total/1024:.1f} KB")
