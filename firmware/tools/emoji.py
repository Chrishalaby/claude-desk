#!/usr/bin/env python3
"""Reaction emoji sets -> 16-colour 4-bit PROGMEM bitmaps pre-composited on black. Generates src/reactions.h.

Sets (the desk owner picks one on the settings page):
  0 pixel   original pixel art (tools/pixel_emoji.py)            default
  1 fluent  Microsoft Fluent Emoji, flat style                   MIT
  2 twemoji Twemoji (Twitter)                                    CC-BY 4.0
  3 noto    Google Noto Emoji                                    Apache 2.0

The pixel set is compiled into the firmware (src/reactions.h); the others become packs the hub serves.

Usage (Iconify JSON packs from npm):
  npm pack @iconify-json/fluent-emoji-flat @iconify-json/twemoji @iconify-json/noto
  for f in iconify-json-*.tgz; do mkdir -p ${f%.tgz}; tar xzf $f -C ${f%.tgz}; done
  python3 tools/emoji.py <fluent icons.json> <twemoji icons.json> <noto icons.json> src/reactions.h ../hub/packs
Needs rsvg-convert (librsvg) and Pillow.
"""
import io, json, subprocess, sys
from PIL import Image

ORDER = [  # reaction id, icon name in the Iconify packs
    ("wave", "waving-hand"), ("thumbs", "thumbs-up"), ("laugh", "face-with-tears-of-joy"),
    ("coffee", "hot-beverage"), ("fire", "fire"), ("heart", "red-heart"),
    ("hug", ["hugging-face", "smiling-face-with-open-hands"]), ("kiss", "kiss-mark"), ("goodnight", "crescent-moon"),
    ("missyou", "pleading-face"),
]
SMALL = ["wave", "heart"]          # 44 px versions for the message card header
BG = (0, 0, 0)                     # cards are pure black


def svg_of(icons, names):
    ic = None
    for name in ([names] if isinstance(names, str) else names):
        ic = icons["icons"].get(name)
        if not ic and name in icons.get("aliases", {}):
            ic = icons["icons"][icons["aliases"][name]["parent"]]
        if ic:
            break
    w, h = ic.get("width", icons.get("width", 16)), ic.get("height", icons.get("height", 16))
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}">{ic["body"]}</svg>'


def raster(svg, size):
    png = subprocess.run(["rsvg-convert", "-w", str(size * 4), "-h", str(size * 4), "-b", "#000000"],
                         input=svg.encode(), capture_output=True, check=True).stdout
    im = Image.open(io.BytesIO(png)).convert("RGB").resize((size, size), Image.LANCZOS)
    return im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)


def c565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def emit(lines, cname, q):
    w, h = q.size
    pal = (q.getpalette() or [])[:48]
    pal += [0] * (48 - len(pal))
    data = list(q.get_flattened_data() if hasattr(q, "get_flattened_data") else q.getdata())
    if len(data) % 2:
        data.append(0)
    packed = bytes((data[i] << 4) | data[i + 1] for i in range(0, len(data), 2))
    lines.append(f"static const uint8_t {cname}_px[] PROGMEM = {{" + ",".join(f"0x{b:02x}" for b in packed) + "};")
    p = ",".join(f"0x{c565(*pal[i*3:i*3+3]):04x}" for i in range(16))
    lines.append(f"static const EmojiImg {cname} PROGMEM = {{{w}, {h}, {{{p}}}, {cname}_px}};")
    return len(packed)


def pack_bytes(entries):
    """entries: list of (name, quantized image) -> CDPK v1 bytes (see docs/PROTOCOL.md section 9)."""
    import struct
    hdr_size = 8 + 56 * len(entries)
    blobs, metas, off = [], [], hdr_size
    for name, q in entries:
        w, h = q.size
        pal = (q.getpalette() or [])[:48]
        pal += [0] * (48 - len(pal))
        data = list(q.get_flattened_data() if hasattr(q, "get_flattened_data") else q.getdata())
        if len(data) % 2:
            data.append(0)
        blob = bytes((data[i] << 4) | data[i + 1] for i in range(0, len(data), 2))
        metas.append(struct.pack("<16sBBHI", name.encode()[:15], w, h, 0, off) +
                     struct.pack("<16H", *[c565(*pal[i*3:i*3+3]) for i in range(16)]))
        blobs.append(blob)
        off += len(blob)
    return b"CDPK" + struct.pack("<BBH", 1, len(entries), 0) + b"".join(metas) + b"".join(blobs)


def preview(entries, path):
    from PIL import Image
    big = [q.convert("RGB") for n, q in entries if not n.endswith("_s")]
    strip = Image.new("RGB", (len(big) * 84, 84), (0, 0, 0))
    for i, im in enumerate(big):
        strip.paste(im, (i * 84 + 2, 2))
    strip.save(path)


if __name__ == "__main__":
    import hashlib, os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import pixel_emoji
    packs = [json.load(open(p)) for p in sys.argv[1:4]]
    out_h, packs_dir = sys.argv[4], sys.argv[5]
    q16 = lambda im: im.quantize(16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)

    # built-in set: original pixel art -> src/reactions.h
    lines = ["// Generated by tools/emoji.py: built-in reaction set (original pixel art). Other sets are",
             "// downloadable packs served by the hub (see docs/PROTOCOL.md section 9). Do not edit.",
             "#pragma once", "#include <stdint.h>", '#include "font.h"',
             "struct EmojiImg { uint8_t w, h; uint16_t pal[16]; const uint8_t *px; };"]
    for rid, _ in ORDER:
        emit(lines, f"P_{rid.upper()}", q16(pixel_emoji.image(rid, 5)))
        if rid in SMALL:
            emit(lines, f"P_{rid.upper()}_S", q16(pixel_emoji.image(rid, 3)))
    lines.append("static const char *const REACT_NAMES[] = {" + ",".join(f'"{r}"' for r, _ in ORDER) + "};")
    lines.append(f"#define REACT_COUNT {len(ORDER)}")
    lines.append("static const EmojiImg *const REACT_IMG[REACT_COUNT] PROGMEM = {" + ",".join(f"&P_{r.upper()}" for r, _ in ORDER) + "};")
    open(out_h, "w").write("\n".join(lines) + "\n")

    # downloadable packs -> hub/packs/<id>.bin + .png + index.json
    os.makedirs(packs_dir, exist_ok=True)
    meta = [("fluent", "Fluent", "MIT (Microsoft Fluent Emoji)"), ("twemoji", "Twemoji", "CC-BY 4.0 (Twemoji)"),
            ("noto", "Noto", "Apache 2.0 (Google Noto Emoji)")]
    index = []
    for (pid, pname, lic), pack in zip(meta, packs):
        entries = []
        for rid, name in ORDER:
            svg = svg_of(pack, name)
            entries.append((rid, raster(svg, 80)))
        for rid, name in ORDER:
            if rid in SMALL:
                entries.append((rid + "_s", raster(svg_of(pack, name), 44)))
        b = pack_bytes(entries)
        open(f"{packs_dir}/{pid}.bin", "wb").write(b)
        preview(entries, f"{packs_dir}/{pid}.png")
        index.append({"id": pid, "name": pname, "license": lic, "size": len(b), "md5": hashlib.md5(b).hexdigest()})
    pix = [(rid, q16(pixel_emoji.image(rid, 5))) for rid, _ in ORDER]
    preview(pix, f"{packs_dir}/pixel.png")
    json.dump({"packs": index}, open(f"{packs_dir}/index.json", "w"), indent=2)
    print("packs:", ", ".join(f"{p['id']} {p['size']//1024} KB" for p in index))
